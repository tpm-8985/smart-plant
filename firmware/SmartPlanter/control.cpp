// 狀態與轉換（與 docs/main-flow.md 的狀態圖一致）：
//   IDLE 待機
//     - 太乾，且 isPumpAllowed() 為 true → 依缺水程度算出澆水時間，開水泵，進入 WATERING
//     - 太濕 → 開風扇，進入 DRYING
