//     - 澆水時間到，或 isPumpAllowed() 變成 false（途中低水位）→ 關水泵，進入 SOAKING
//   SOAKING 等待滲透
//     - 不依讀值做任何決定；滿 SOAK_WAIT_MS → 回到 IDLE 重新判斷
//   DRYING 風乾
//     - 濕度回到正常範圍 → 關風扇，回到 IDLE
//   FAULT 感測器異常
//     - 不論目前在哪個狀態，只要 moisture 為 -1 → 關水泵與風扇，進入 FAULT
//     - 讀值恢復正常 → 回到 IDLE 重新判斷
